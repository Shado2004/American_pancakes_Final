const fs = require('fs');
const schema = JSON.parse(fs.readFileSync('scripts/flo-schema.json', 'utf8'));

// Boolean columns list based on names
function isBooleanColumn(colName) {
  const c = colName.toLowerCase();
  return c.startsWith('is_') || 
         c.startsWith('has_') || 
         c.startsWith('allow_') || 
         c.startsWith('require_') || 
         c.endsWith('_enabled') || 
         c.endsWith('_required') || 
         c === 'no_packaging' || 
         c === 'inherit_parent_tax_category' || 
         c === 'cash_drawer_pulse_enabled' ||
         c === 'track_inventory';
}

function isMoneyColumn(colName) {
  const c = colName.toLowerCase();
  return c === 'price' || 
         c === 'cost' || 
         c === 'subtotal' || 
         c === 'total' || 
         c === 'tax_amount' || 
         c === 'discount_amount' || 
         c === 'delivery_charge' || 
         c === 'packaging_charge' || 
         c === 'service_charge' || 
         c === 'round_off' || 
         c === 'paid_amount' || 
         c === 'balance' || 
         c === 'unit_cost' || 
         c === 'amount' || 
         c === 'customer_charge_per_unit' || 
         c === 'recovered_ingredient_cost' || 
         c === 'recovered_plate_cost';
}

const tableStatements = [];
const indexStatements = [];

// Track table creation order so references are ordered properly or FKs added at the end
const tableNames = Object.keys(schema);

for (const tableName of tableNames) {
  const info = schema[tableName];
  const colDefs = [];
  const primaryKeys = [];

  for (const col of info.columns) {
    let colType = col.type.toUpperCase();
    let pgType = 'TEXT';
    const isPk = col.pk > 0;

    if (isPk && colType.includes('INT') && info.columns.filter(c => c.pk > 0).length === 1) {
      pgType = 'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY';
    } else {
      if (isBooleanColumn(col.name) && colType.includes('INT')) {
        pgType = 'SMALLINT';
      } else if (isMoneyColumn(col.name) && (colType === 'REAL' || colType.includes('NUM') || colType.includes('DEC'))) {
        pgType = 'NUMERIC(12,2)';
      } else if (colType === 'REAL') {
        pgType = 'DOUBLE PRECISION';
      } else if (colType.includes('INT')) {
        pgType = 'INTEGER';
      } else if (colType === 'BLOB') {
        pgType = 'BYTEA';
      } else {
        pgType = 'TEXT';
      }

      let def = `"${col.name}" ${pgType}`;
      if (col.notnull && !isPk) {
        def += ' NOT NULL';
      }
      if (col.dflt_value !== null && col.dflt_value !== undefined) {
        let dflt = col.dflt_value;
        if (dflt.toUpperCase() === 'CURRENT_TIMESTAMP') {
          def += " DEFAULT TO_CHAR(NOW() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')";
        } else {
          def += ` DEFAULT ${dflt}`;
        }
      }
      colDefs.push(def);

      if (isPk) {
        primaryKeys.push(`"${col.name}"`);
      }
    }
  }

  // Composite primary keys if not already handled
  if (primaryKeys.length > 0 && !colDefs.some(d => d.includes('PRIMARY KEY'))) {
    colDefs.push(`PRIMARY KEY (${primaryKeys.join(', ')})`);
  }

  tableStatements.push(`CREATE TABLE IF NOT EXISTS "${tableName}" (\n  ${colDefs.join(',\n  ')}\n);`);
}

const outDir = 'main/db/migrations/postgres';
if (!fs.existsSync(outDir)) {
  fs.mkdirSync(outDir, { recursive: true });
}

const fullSql = [
  '-- ==============================================================================',
  '-- Consolidated PostgreSQL Schema for American Pancakes POS',
  '-- Compatible with Supabase PostgreSQL 15+',
  '-- ==============================================================================',
  '',
  '-- Migration ledger to track applied migrations',
  'CREATE TABLE IF NOT EXISTS schema_migrations (',
  '  version INTEGER PRIMARY KEY,',
  '  name TEXT NOT NULL,',
  '  applied_at TEXT DEFAULT TO_CHAR(NOW() AT TIME ZONE \'UTC\', \'YYYY-MM-DD HH24:MI:SS\')',
  ');',
  '',
  ...tableStatements,
  ''
].join('\n');

fs.writeFileSync(`${outDir}/schema.sql`, fullSql);
console.log(`Generated ${outDir}/schema.sql for ${tableNames.length} tables.`);
